"""
Evaluate grounded answers generated by the local Ollama model.

Ollama must be running before this evaluation:

    ollama serve

Run:

    python -m src.eval.evaluate_answers
"""

from __future__ import annotations

import re
import time

from src.generation.generate_answer import generate_answer


TEST_QUESTIONS = [
    (
        "What was Microsoft's revenue in fiscal year 2026?"
    ),
    (
        "Which company had the highest operating margin "
        "in fiscal year 2025?"
    ),
    (
        "Why did Microsoft's revenue increase "
        "in fiscal year 2026?"
    ),
]


def extract_citations(answer: str) -> set[str]:
    """Extract labels such as N1 and T2 from an answer."""

    return set(
        re.findall(
            r"\[(N\d+|T\d+)\]",
            answer,
        )
    )


def evaluate_answer(question: str) -> dict:
    """Generate and evaluate one answer."""

    start_time = time.perf_counter()

    result = generate_answer(
        question=question,
        top_k=5,
    )

    elapsed = time.perf_counter() - start_time

    answer = result["answer"]
    citations = extract_citations(answer)

    available_labels = {
        source["label"]
        for source in result["sources"]
    }

    invalid_citations = (
        citations - available_labels
    )

    checks = {
        "answer_not_empty": bool(answer.strip()),
        "citation_present": bool(citations),
        "all_citations_valid": not invalid_citations,
        "source_metadata_present": all(
            source.get("source_url")
            and source.get("accession_number")
            for source in result["sources"]
        ),
        "answer_is_concise": (
            len(answer.split()) <= 350
        ),
    }

    return {
        "question": question,
        "answer": answer,
        "citations": sorted(citations),
        "available_labels": sorted(
            available_labels
        ),
        "invalid_citations": sorted(
            invalid_citations
        ),
        "latency_seconds": elapsed,
        "checks": checks,
        "passed": all(checks.values()),
    }


def main() -> None:
    print("Answer-Grounding Evaluation")
    print("=" * 80)

    results = []

    for index, question in enumerate(
        TEST_QUESTIONS,
        start=1,
    ):
        print(
            f"\nGenerating answer {index}/"
            f"{len(TEST_QUESTIONS)}..."
        )

        result = evaluate_answer(question)
        results.append(result)

        status = (
            "PASS"
            if result["passed"]
            else "FAIL"
        )

        print(
            f"\n{index}. [{status}] "
            f"{result['question']}"
        )
        print(
            f"   Latency: "
            f"{result['latency_seconds']:.2f}s"
        )
        print(
            f"   Citations used: "
            f"{result['citations']}"
        )
        print(
            f"   Available labels: "
            f"{result['available_labels']}"
        )

        if result["invalid_citations"]:
            print(
                f"   Invalid citations: "
                f"{result['invalid_citations']}"
            )

        for check, passed in result["checks"].items():
            label = "PASS" if passed else "FAIL"
            print(f"   {label}: {check}")

        print("\n   Answer:")
        print("   " + result["answer"].replace(
            "\n",
            "\n   ",
        ))

    passed_count = sum(
        result["passed"]
        for result in results
    )

    total_count = len(results)

    average_latency = sum(
        result["latency_seconds"]
        for result in results
    ) / total_count

    print("\nSummary")
    print("=" * 80)
    print(
        f"Passed: {passed_count}/{total_count} "
        f"({passed_count / total_count:.1%})"
    )
    print(
        f"Average generation latency: "
        f"{average_latency:.2f}s"
    )


if __name__ == "__main__":
    main()